const assert = require('node:assert/strict');
const fs = require('node:fs');
const { chromium } = require('../melvin-portfolio/node_modules/playwright');

(async () => {
  const html = fs.readFileSync('melvin-portfolio/dist/index.html', 'utf8')
    .replace(/<meta\b[^>]*http-equiv="Content-Security-Policy"[^>]*>/i, '')
    .replace(/<script>([\s\S]*?)<\/script>/g, '');
  const runtime = fs.readFileSync('.work/unslop-runtime.js', 'utf8');
  const browser = await chromium.launch({ headless: true, executablePath: 'C:/Users/m-gamana/AppData/Local/ms-playwright/chromium_headless_shell-1200/chrome-headless-shell-win64/chrome-headless-shell.exe' });
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
  const errors = [];
  page.on('pageerror', (error) => errors.push(error.message));
  await page.setContent(html, { waitUntil: 'domcontentloaded' });
  await page.evaluate(() => {
    document.querySelectorAll('[data-filter], [data-project-count], [data-reset-filter]').forEach((node) => node.remove());
    document.body.insertAdjacentHTML('afterbegin', '<div data-preview><img data-preview-image width="100" height="100" src="data:image/svg+xml,%3Csvg xmlns=%22http://www.w3.org/2000/svg%22 width=%221%22 height=%221%22%3E%3C/svg%3E"><p data-preview-status role="status" hidden>Loading game preview…</p><p data-preview-error hidden>Preview unavailable.</p></div>');
    const symbol = document.createElementNS('http://www.w3.org/2000/svg', 'symbol');
    symbol.id = 'i-check';
    document.querySelector('defs').append(symbol);
    Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: (text) => new Promise((resolve, reject) => { window.clipboardText = text; window.resolveCopy = resolve; window.rejectCopy = reject; }) } });
  });
  await page.waitForFunction(() => { const image = document.querySelector('[data-preview-image]'); return image.complete && image.naturalWidth > 0; });
  await page.addScriptTag({ content: runtime });
  assert.deepEqual(errors, [], 'Runtime must survive removed filter controls');
  assert.equal(await page.locator('[data-preview]').getAttribute('aria-busy'), 'false');
  assert.equal(await page.locator('[data-preview]').evaluate((node) => node.classList.contains('is-loaded')), true, 'Cached preview is ready');
  assert.equal(await page.locator('.skill-panel h3').count(), 0, 'No redundant category heading');
  await page.locator('[data-project="hangman"]').click();
  assert.equal(await page.locator('#project-dialog').evaluate((node) => node.open), true);
  assert.equal(await page.locator('#project-dialog-content .project-tech').count(), 1);
  assert.equal(await page.locator('#project-dialog-content .tags').count(), 0);
  assert.equal(await page.locator('#project-dialog .dialog-actions .primary').count(), 1);
  assert.equal(await page.locator('#project-dialog .dialog-actions .icon use').first().getAttribute('href'), '#i-up-right');
  await page.keyboard.press('Escape');
  await page.locator('#copy-email').click();
  assert.equal(await page.locator('#copy-email').isDisabled(), true);
  assert.equal(await page.locator('#copy-email').getAttribute('aria-busy'), 'true');
  assert.equal(await page.locator('#copy-status').textContent(), 'Copying…');
  await page.evaluate(() => window.resolveCopy());
  await page.waitForFunction(() => !document.querySelector('#copy-email').disabled);
  assert.equal(await page.locator('#copy-email use').getAttribute('href'), '#i-check');
  assert.equal(await page.locator('#copy-status').textContent(), 'Email address copied.');
  await page.locator('#copy-email').click();
  await page.evaluate(() => window.rejectCopy(new Error('Denied')));
  await page.waitForFunction(() => !document.querySelector('#copy-email').disabled);
  assert.match(await page.locator('#copy-status').textContent(), /unavailable/);
  assert.equal(await page.locator('#copy-email use').getAttribute('href'), '#i-copy');
  await page.locator('#name').fill('Portfolio Reviewer');
  await page.locator('#email').fill('reviewer@example.com');
  await page.locator('#message').fill('A useful portfolio inquiry for testing.');
  await page.locator('#contact-form button[type="submit"]').click();
  assert.equal(await page.locator('#contact-form button[type="submit"]').isDisabled(), true);
  assert.match(await page.locator('#contact-form button[type="submit"]').textContent(), /Draft ready/);
  assert.equal(await page.locator('#draft-result').isVisible(), true);
  assert.match(await page.locator('#email-draft').getAttribute('href'), /^mailto:melvingamanajr@gmail\.com\?subject=/);
  await page.locator('#message').fill('A changed inquiry resets the prepared draft.');
  assert.equal(await page.locator('#draft-result').isVisible(), false);
  assert.equal(await page.locator('#contact-form button[type="submit"]').isDisabled(), false);
  await page.locator('[data-preview-image]').evaluate((image) => { image.src = 'data:image/png;base64,broken'; });
  await page.waitForFunction(() => document.querySelector('[data-preview]').classList.contains('is-error'));
  assert.equal(await page.locator('[data-preview]').getAttribute('aria-busy'), 'false');
  assert.equal(await page.locator('[data-preview-status]').isVisible(), false);
  assert.equal(await page.locator('[data-preview-error]').isVisible(), true);
  assert.deepEqual(errors, []);
  const loadingPage = await browser.newPage();
  let previewRequest;
  await loadingPage.route('https://portfolio.test/preview.svg', (route) => { previewRequest = route; });
  const loadingFixture = '<div data-preview><img data-preview-image width="100" height="100" src="https://portfolio.test/preview.svg"><p data-preview-status role="status" hidden>Loading game preview…</p><p data-preview-error hidden>Preview unavailable.</p></div>';
  await loadingPage.setContent(html.replace('<body>', `<body>${loadingFixture}`), { waitUntil: 'domcontentloaded' });
  await loadingPage.addScriptTag({ content: runtime });
  assert.equal(await loadingPage.locator('[data-preview]').getAttribute('aria-busy'), 'true');
  assert.equal(await loadingPage.locator('[data-preview-status]').isVisible(), true);
  await previewRequest.fulfill({ status: 200, contentType: 'image/svg+xml', body: '<svg xmlns="http://www.w3.org/2000/svg" width="100" height="100"></svg>' });
  await loadingPage.waitForFunction(() => document.querySelector('[data-preview]').classList.contains('is-loaded'));
  assert.equal(await loadingPage.locator('[data-preview]').getAttribute('aria-busy'), 'false');
  assert.equal(await loadingPage.locator('[data-preview-status]').isVisible(), false);
  await browser.close();
  console.log('PASS runtime without filters; pending/cached/loaded/error preview; dialog; clipboard pending/success/rejection; draft preparation/reset');
})().catch((error) => { console.error(error); process.exitCode = 1; });
